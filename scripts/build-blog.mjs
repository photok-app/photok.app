// Builds the static blog from content/blog/*.md into blog/.
// Runs in CI on push (see .github/workflows/build-blog.yml) or locally: cd scripts && npm run build

import { readFile, writeFile, readdir, mkdir, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { marked } from 'marked';
import { parse as parseYaml } from 'yaml';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CONTENT_DIR = path.join(ROOT, 'content/blog');
const TEMPLATE_DIR = path.join(ROOT, 'templates');
const OUT_DIR = path.join(ROOT, 'blog');
const SITEMAP = path.join(ROOT, 'sitemap.xml');

const SITE_URL = 'https://photok.app';
const BLOG_URL = `${SITE_URL}/blog/`;
const DEFAULT_IMAGE = 'https://raw.githubusercontent.com/leonlatsch/Photok/main/fastlane/metadata/android/en-US/images/icon.png';
const GENERATED_MARKER = 'generated by scripts/build-blog.mjs from content/blog – edit the markdown, not this file';

const REQUIRED_FIELDS = ['title', 'description', 'date', 'author'];
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;
const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

// --- helpers ---

const escapeHtml = (value) => String(value)
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;')
  .replace(/'/g, '&#39;');

// JSON for inline <script> blocks; escaping "<" prevents a "</script>" in content from closing the tag
const jsonLd = (data) => JSON.stringify(data, null, 2).replace(/</g, '\\u003c');

const indent = (text, spaces) => text.split('\n').map((line) => (line ? ' '.repeat(spaces) + line : line)).join('\n');

// Single pass so placeholders inside substituted values (e.g. a post mentioning "{{title}}") stay untouched
function render(template, values, name) {
  return template.replace(/\{\{(\w+)\}\}/g, (_, key) => {
    if (!(key in values)) throw new Error(`Template ${name} uses unknown placeholder {{${key}}}`);
    return values[key];
  });
}

// Dates stay plain YYYY-MM-DD strings; the yaml core schema doesn't turn them into Date objects
function normalizeDate(value, field, file) {
  const str = value instanceof Date ? value.toISOString().slice(0, 10) : String(value).trim();
  if (!DATE_RE.test(str)) throw new Error(`${file}: "${field}" must be YYYY-MM-DD, got "${value}"`);
  return str;
}

function formatDate(isoDate) {
  const [year, month, day] = isoDate.split('-').map(Number);
  return `${MONTHS[month - 1]} ${day}, ${year}`;
}

function rfc822(isoDate) {
  const [year, month, day] = isoDate.split('-').map(Number);
  return new Date(Date.UTC(year, month - 1, day)).toUTCString();
}

const latestDate = (posts) => (posts.length ? posts.map((p) => p.updated ?? p.date).sort().at(-1) : null);

function parseFrontMatter(raw, file) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) throw new Error(`${file}: missing front matter (--- block at the top)`);
  const data = parseYaml(match[1]) ?? {};
  return { data, body: match[2] };
}

// --- load posts ---

async function loadPosts() {
  const files = (await readdir(CONTENT_DIR)).filter((f) => f.endsWith('.md') && !f.startsWith('_')).sort();
  const posts = [];
  const slugs = new Map();

  for (const file of files) {
    const { data, body } = parseFrontMatter(await readFile(path.join(CONTENT_DIR, file), 'utf8'), file);
    if (data.draft === true) continue;

    const missing = REQUIRED_FIELDS.filter((field) => data[field] == null || String(data[field]).trim() === '');
    if (missing.length) throw new Error(`${file}: missing required front matter: ${missing.join(', ')}`);

    const slug = String(data.slug ?? file.replace(/\.md$/, ''));
    if (!SLUG_RE.test(slug)) throw new Error(`${file}: slug "${slug}" must be lowercase letters, digits and dashes`);
    if (slugs.has(slug)) throw new Error(`${file}: slug "${slug}" already used by ${slugs.get(slug)}`);
    slugs.set(slug, file);

    const tags = data.tags == null ? [] : (Array.isArray(data.tags) ? data.tags : [data.tags]).map(String);
    const date = normalizeDate(data.date, 'date', file);
    const updated = data.updated == null ? null : normalizeDate(data.updated, 'updated', file);
    const words = body.split(/\s+/).filter(Boolean).length;

    posts.push({
      file,
      slug,
      url: `${BLOG_URL}${slug}/`,
      title: String(data.title),
      description: String(data.description),
      author: String(data.author),
      authorUrl: data.author_url ? String(data.author_url) : null,
      date,
      updated,
      tags,
      image: data.image ? String(data.image) : null,
      readingMinutes: Math.max(1, Math.round(words / 200)),
      html: marked.parse(body).trim(),
    });
  }

  // Newest first; slug as tiebreaker keeps the output stable
  return posts.sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));
}

// --- renderers ---

function renderPost(post, templates) {
  const authorHtml = post.authorUrl
    ? `<a href="${escapeHtml(post.authorUrl)}" rel="author">${escapeHtml(post.author)}</a>`
    : escapeHtml(post.author);
  const updatedHtml = post.updated && post.updated !== post.date
    ? ` · Updated <time datetime="${post.updated}">${formatDate(post.updated)}</time>`
    : '';
  const byline = `<time datetime="${post.date}">${formatDate(post.date)}</time>${updatedHtml} · ${authorHtml} · ${post.readingMinutes} min read`;
  const tags = post.tags.length
    ? `      <ul class="blog-tags">${post.tags.map((t) => `<li>${escapeHtml(t)}</li>`).join('')}</ul>`
    : '';
  const cover = post.image
    ? `    <img class="blog-cover" src="${escapeHtml(post.image)}" alt="" />`
    : '';

  const author = { '@type': 'Person', name: post.author };
  if (post.authorUrl) author.url = post.authorUrl;

  return render(templates.post, {
    title: escapeHtml(post.title),
    description: escapeHtml(post.description),
    author: escapeHtml(post.author),
    url: post.url,
    image: escapeHtml(post.image ?? DEFAULT_IMAGE),
    twitter_card: post.image ? 'summary_large_image' : 'summary',
    date: post.date,
    modified: post.updated ?? post.date,
    byline,
    tags,
    cover,
    content: post.html, // not indented: whitespace inside <pre> is significant
    nav: templates.nav,
    footer: templates.footer,
    generated_marker: GENERATED_MARKER,
    json_ld: jsonLd({
      '@context': 'https://schema.org',
      '@type': 'BlogPosting',
      headline: post.title,
      description: post.description,
      datePublished: post.date,
      dateModified: post.updated ?? post.date,
      author,
      publisher: { '@type': 'Organization', name: 'Photok', logo: { '@type': 'ImageObject', url: DEFAULT_IMAGE } },
      image: post.image ?? DEFAULT_IMAGE,
      mainEntityOfPage: post.url,
      ...(post.tags.length && { keywords: post.tags.join(', ') }),
    }),
  }, 'blog-post.html');
}

function renderIndex(posts, templates) {
  const cards = posts.length
    ? posts.map((post) => [
      `<a class="blog-card" href="/blog/${post.slug}/">`,
      `  <p class="blog-meta"><time datetime="${post.date}">${formatDate(post.date)}</time> · ${escapeHtml(post.author)}</p>`,
      `  <h2>${escapeHtml(post.title)}</h2>`,
      `  <p>${escapeHtml(post.description)}</p>`,
      `  <span class="text-link">Read post →</span>`,
      `</a>`,
    ].join('\n')).join('\n')
    : '<p class="blog-empty">No posts yet. Check back soon.</p>';

  return render(templates.index, {
    url: BLOG_URL,
    posts: indent(cards, 6),
    nav: templates.nav,
    footer: templates.footer,
    generated_marker: GENERATED_MARKER,
    json_ld: jsonLd({
      '@context': 'https://schema.org',
      '@type': 'Blog',
      name: 'Photok Blog',
      url: BLOG_URL,
      blogPost: posts.map((post) => ({
        '@type': 'BlogPosting',
        headline: post.title,
        url: post.url,
        datePublished: post.date,
        author: { '@type': 'Person', name: post.author },
      })),
    }),
  }, 'blog-index.html');
}

function renderFeed(posts) {
  const items = posts.map((post) => `    <item>
      <title>${escapeHtml(post.title)}</title>
      <link>${post.url}</link>
      <guid isPermaLink="true">${post.url}</guid>
      <pubDate>${rfc822(post.date)}</pubDate>
      <dc:creator>${escapeHtml(post.author)}</dc:creator>
      <description>${escapeHtml(post.description)}</description>
    </item>`).join('\n');
  // lastBuildDate comes from the newest post, not the clock, so rebuilding without changes produces no diff
  const lastBuild = posts.length ? `\n    <lastBuildDate>${rfc822(latestDate(posts))}</lastBuildDate>` : '';

  return `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:dc="http://purl.org/dc/elements/1.1/">
  <channel>
    <title>Photok Blog</title>
    <link>${BLOG_URL}</link>
    <description>News, guides and behind-the-scenes posts about Photok.</description>
    <language>en</language>${lastBuild}
    <atom:link href="${BLOG_URL}feed.xml" rel="self" type="application/rss+xml" />
${items}
  </channel>
</rss>
`;
}

async function updateSitemap(posts) {
  const sitemap = await readFile(SITEMAP, 'utf8');
  const blockRe = /(<!-- blog:start[^>]*-->)[\s\S]*?(<!-- blog:end -->)/;
  if (!blockRe.test(sitemap)) throw new Error('sitemap.xml: missing <!-- blog:start --> / <!-- blog:end --> markers');

  const entry = (loc, lastmod, priority) => [
    '',
    '  <url>',
    `    <loc>${loc}</loc>`,
    ...(lastmod ? [`    <lastmod>${lastmod}</lastmod>`] : []),
    '    <changefreq>monthly</changefreq>',
    `    <priority>${priority}</priority>`,
    '  </url>',
  ].join('\n');
  const entries = [entry(BLOG_URL, latestDate(posts), '0.6'), ...posts.map((p) => entry(p.url, p.updated ?? p.date, '0.5'))].join('\n');

  await writeFile(SITEMAP, sitemap.replace(blockRe, (_, start, end) => `${start}\n${entries}\n\n  ${end}`));
}

// Deletes post folders this script generated earlier whose source is gone (renamed, deleted or turned into a draft)
async function removeStalePosts(posts) {
  const live = new Set(posts.map((p) => p.slug));
  const entries = await readdir(OUT_DIR, { withFileTypes: true });
  for (const entry of entries) {
    if (!entry.isDirectory() || live.has(entry.name)) continue;
    const indexFile = path.join(OUT_DIR, entry.name, 'index.html');
    if (existsSync(indexFile) && (await readFile(indexFile, 'utf8')).includes(GENERATED_MARKER)) {
      await rm(path.join(OUT_DIR, entry.name), { recursive: true });
      console.log(`removed stale blog/${entry.name}/`);
    }
  }
}

// --- main ---

const templates = {
  post: await readFile(path.join(TEMPLATE_DIR, 'blog-post.html'), 'utf8'),
  index: await readFile(path.join(TEMPLATE_DIR, 'blog-index.html'), 'utf8'),
  nav: indent((await readFile(path.join(TEMPLATE_DIR, 'partial-nav.html'), 'utf8')).trimEnd(), 2),
  footer: indent((await readFile(path.join(TEMPLATE_DIR, 'partial-footer.html'), 'utf8')).trimEnd(), 2),
};

const posts = await loadPosts();
await mkdir(OUT_DIR, { recursive: true });

for (const post of posts) {
  await mkdir(path.join(OUT_DIR, post.slug), { recursive: true });
  await writeFile(path.join(OUT_DIR, post.slug, 'index.html'), renderPost(post, templates));
}
await writeFile(path.join(OUT_DIR, 'index.html'), renderIndex(posts, templates));
await writeFile(path.join(OUT_DIR, 'feed.xml'), renderFeed(posts));
await updateSitemap(posts);
await removeStalePosts(posts);

console.log(`built ${posts.length} post(s): ${posts.map((p) => p.slug).join(', ') || '-'}`);
